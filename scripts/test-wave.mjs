import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const src=await readFile(new URL('../worker/wave-research-core.js',import.meta.url),'utf8');
const W=new Function(src+';return ChaoweiWave')();
const make=(prices,start='2024-01-01')=>prices.map((close,i)=>({date:new Date(Date.parse(start)+i*86400000).toISOString().slice(0,10),close}));
const prices=[100,99,98,97,98,100,103,106,108,110,109,107,103,99,95,92,94,98,102,106,110];
const rows=W.priceSeries(make(prices),[],'split');
const p={minBars:3,reversal:3,large:10,fast:1};
const all=W.detect(rows,p),partial=W.detect(rows.slice(0,15),p);
assert.ok(all.pivots.length>=2,'at least two confirmed pivots');
assert.deepEqual(partial.pivots,all.pivots.filter(x=>x.confirmIndex<15),'future bars cannot revise confirmed pivots');
assert.ok(all.pivots.every(x=>x.confirmIndex>x.index&&x.confirmDate>=x.date),'a pivot is only usable when confirmed');
const weekly=W.detect(rows.map((x,i)=>({...x,endDate:new Date(Date.parse(x.date)+2*86400000).toISOString().slice(0,10)})),p);
assert.ok(weekly.pivots.every(x=>x.confirmDate>rows[x.confirmIndex].date),'weekly signal date follows the period close');
assert.ok(all.segments.every(s=>s.bars>=p.minBars&&s.speed===Math.abs(s.change)/s.bars),'duration and speed agree');
const ex=make([100,97,98]);
const total=W.priceSeries(ex,[[ex[1].date,3]],'total');
assert.equal(total[1].studyClose,100,'cash distribution must not appear as an artificial total-return loss');
assert.equal(W.priceSeries(ex,[],'split')[1].studyClose,97,'split-only basis retains the price gap');
const cutoff=all.segments.at(-1)?.availableDate;
const summary=W.summary(all.segments,cutoff);
assert.equal(summary.training.count+summary.testing.count,summary.all.count,'training and test periods partition by confirmation date');
const code=JSON.parse(await readFile(new URL('../pages-data/chips/0050.json',import.meta.url),'utf8'));
assert.ok(code.rows.length>=20&&code.rows.every(r=>r.length===9&&r[5]>=0&&r[6]>0&&r[5]<=r[6]&&(r[7]===null||r[7]>=0)&&(r[8]===null||r[8]>=0)),'institutional rows, ownership ratio and margin balances');
assert.ok(code.rows.every((r,i)=>!i||r[0]>code.rows[i-1][0]),'institutional dates ascend');
console.log(`Wave research verified: ${all.pivots.length} pivots, ${all.segments.length} segments; 0050 chip days ${code.rows.length}.`);
