import assert from 'node:assert/strict';
import fs from 'node:fs';
import {parseTwseCalendar,taiwanSession,checkTaiwanQuotes,taiwanTradingAge} from './market-session-health.mjs';
const path='scripts/fixtures/market-health/';
const raw=JSON.parse(fs.readFileSync(path+'twse-calendar-2026.json','utf8'));
const calendar=parseTwseCalendar(raw,2026);
assert.ok(calendar.closed.includes('2026-10-26'));
assert.ok(calendar.closed.includes('2026-02-12'),'settlement-only day has no session');
assert.ok(calendar.open.includes('2026-01-02'),'first trading day is not a holiday');
assert.throws(()=>parseTwseCalendar(raw,2027),/年度/);
const published={'history/market':'2026-11-26','history/0050':'2026-11-26'};
const base={calendar,published,upstream:'2026-11-26',intraday:null,quote:{available:false,reason:'尚無正式成交報價'}};
const at=time=>new Date('2026-11-27T'+time+':00+08:00');
for(const id of ['45885869210','45908107085','45918394508']){
  const fixture=JSON.parse(fs.readFileSync(path+'run-'+id+'.json','utf8'));
  const result=checkTaiwanQuotes({...fixture,calendar,now:new Date(fixture.now)});
  assert.deepEqual(result.errors,[],id+' historical failure no longer mistakes closed hours for an outage');
  assert.equal(result.session.requireLive,false);
  assert.ok(result.series.every(r=>r.date==='2026-11-26'&&r.kind==='confirmed-close-fallback'),'fallback retains the actual close date');
}
for(const time of ['00:30','06:58','08:43','09:09','13:31','23:00'])assert.equal(checkTaiwanQuotes({...base,now:at(time)}).errors.length,0,time);
for(const time of ['09:10','10:00','13:30'])assert.equal(checkTaiwanQuotes({...base,now:at(time)}).errors.length,2,time+' missing both feeds must fail');
const active={...base,now:at('10:00'),intraday:{date:'2026-11-27',time:'09:55:00',index:39128.6},quote:{available:true,date:'2026-11-27',time:'2026-11-27T09:56:00+08:00',price:92.05}};
assert.deepEqual(checkTaiwanQuotes(active).errors,[]);
assert.equal(checkTaiwanQuotes({...active,intraday:{...active.intraday,date:'2026-11-26'}}).errors.length,1,'yesterday cannot masquerade as live');
assert.equal(checkTaiwanQuotes({...active,intraday:null}).errors.length,1,'the old date-present guard cannot skip a missing live feed');
assert.equal(checkTaiwanQuotes({...active,quote:{...active.quote,time:'2026-11-27T09:49:00+08:00'}}).errors.length,1,'stale live quote fails');
assert.equal(checkTaiwanQuotes({...active,quote:{...active.quote,time:null}}).errors.length,1);
assert.equal(checkTaiwanQuotes({...active,quote:{...active.quote,time:'2026-11-27T10:02:00+08:00'}}).errors.length,1,'future time fails');
assert.equal(checkTaiwanQuotes({...base,now:at('08:00'),published:{}}).errors.length,2,'closed does not exempt missing closes');
assert.equal(checkTaiwanQuotes({...base,now:at('08:00'),published:{'history/market':'2026-11-25','history/0050':'2026-11-25'}}).errors.length,2,'closed does not exempt lagging closes');
assert.match(checkTaiwanQuotes({...base,now:at('08:00'),quote:{available:false,reason:'行情金鑰尚未設定'}}).errors[0],/設定異常/);
assert.throws(()=>taiwanSession(at('08:00'),null),/缺少/,'calendar failure cannot silently skip live checks');
assert.equal(taiwanSession(new Date('2026-11-28T10:00:00+08:00'),calendar).phase,'holiday');
assert.equal(taiwanSession(new Date('2026-10-26T10:00:00+08:00'),calendar).phase,'holiday');
assert.equal(taiwanSession(new Date('2026-01-02T10:00:00+08:00'),calendar).phase,'trading');
assert.equal(taiwanTradingAge('2026-02-11',new Date('2026-02-23T08:00:00+08:00'),calendar),1,'long New Year closure must not count as missed trading days');
assert.equal(taiwanTradingAge('2026-11-20',new Date('2026-11-23T08:00:00+08:00'),calendar),1);
console.log('PASS Taiwan session health: 3 archived failures replayed; preopen/opening/live/closed, weekends, official holidays, absent/stale/future live data, missing/lagging closes, calendar and configuration errors.');
